        ("2024-3-11", "2024-3-11"),  # месяц 1 цифра
        ("2024-03-1", "2024-03-1"),  # день 1 цифра
        ("2024-03-111", "2024-03-111"),  # день 3 цифры
        # 7. Пробелы и лишние символы
        ("  2024-03-11  ", "11.03.2024"),  # пробелы по краям
        ("2024-03-11 extra", "2024-03-11 extra"),  # текст после даты
        ("pre 2024-03-11", "pre 2024-03-11"),  # текст до даты
        # 8. Специальные случаи с T
        ("2024-03-11T", "11.03.2024"),  # T без времени
        ("T2024-03-11", "T2024-03-11"),  # T в начале
        ("2024-03-11Text", "11.03.2024"),  # T в середине слова
